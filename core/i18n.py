class LocalizationManager:
    """Provides PC language auto-detection and runtime translation across en-US, pt-BR, and es-ES."""

    def __init__(self, preference: str = "auto") -> None:
        self._preference = "auto"
        self._active_language = "en-US"
        self.set_preference(preference)

    @property
    def preference(self) -> str:
        return self._preference

    @property
    def active_language(self) -> str:
        return self._active_language

    def set_preference(self, preference: str) -> str:
        """Set configured language ('auto', 'en-US', 'pt-BR', 'es-ES') and return resolved code."""
        cleaned = (preference or "auto").strip()
        if cleaned.lower() in ("auto", "system"):
            self._preference = "auto"
            self._active_language = self.detect_system_language()
        else:
            self._active_language = self.normalize_language(cleaned)
            self._preference = self._active_language
        return self._active_language

    def tr(self, key: str, **kwargs: Any) -> str:
        """Translate key using active language with fallback to en-US."""
        table = TRANSLATIONS.get(self._active_language, TRANSLATIONS["en-US"])
        template = table.get(key) or TRANSLATIONS["en-US"].get(key) or key
        if kwargs:
            try:
                return template.format(**kwargs)
            except (KeyError, ValueError):
                return template
        return template

    def tr_plural(self, base_key: str, count: int, **kwargs: Any) -> str:
        """Select singular, plural, or optional zero translation variant for count."""
        table = TRANSLATIONS.get(self._active_language, TRANSLATIONS["en-US"])
        en_table = TRANSLATIONS["en-US"]
        if count == 0 and (f"{base_key}_zero" in table or f"{base_key}_zero" in en_table):
            chosen_key = f"{base_key}_zero"
        elif count == 1:
            chosen_key = f"{base_key}_one"
        else:
            chosen_key = f"{base_key}_many"
        return self.tr(chosen_key, count=count, **kwargs)

    def date_format_pattern(self) -> str:
        """Return active strftime pattern ('%d/%m/%Y %H:%M' for pt-BR/es-ES, '%Y-%m-%d %H:%M' for en-US)."""
        if self._active_language in ("pt-BR", "es-ES"):
            return "%d/%m/%Y %H:%M"
        return "%Y-%m-%d %H:%M"

    def format_timestamp(self, epoch: int) -> str:
        """Format a Unix epoch timestamp in the active UI language date pattern."""
        if epoch <= 0:
            return "-"
        try:
            return datetime.fromtimestamp(int(epoch)).strftime(self.date_format_pattern())
        except (OSError, OverflowError, ValueError):
            return "-"

    def format_date_str(self, raw: str) -> str:
        """Format an ISO-like date string from history/storage in the active UI language."""
        cleaned = (raw or "").strip()
        if not cleaned:
            return "-"
        for pat in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y-%m-%dT%H:%M:%S", "%d/%m/%Y %H:%M"):
            try:
                parsed = datetime.strptime(cleaned, pat)
                return parsed.strftime(self.date_format_pattern())
            except ValueError:
                continue
        return cleaned

    @classmethod
    def normalize_language(cls, code: str) -> str:
        """Map any Windows/POSIX locale string to 'pt-BR', 'es-ES', or 'en-US'."""
        lower = (code or "").strip().lower().replace("_", "-")
        if lower.startswith("pt") or "portuguese" in lower:
            return "pt-BR"
        if lower.startswith("es") or "spanish" in lower:
            return "es-ES"
        return "en-US"

    @classmethod
    def detect_system_language(cls) -> str:
        """Detect the OS UI language on Windows or POSIX systems."""
        try:
            kernel32 = getattr(ctypes, "windll", None)
            if kernel32 is not None:
                lang_id = int(kernel32.kernel32.GetUserDefaultUILanguage())
                win_locale = locale.windows_locale.get(lang_id)
                if win_locale:
                    return cls.normalize_language(win_locale)
        except Exception:
            pass

        try:
            from PySide6.QtCore import QLocale

            qt_name = QLocale.system().name()
            if qt_name:
                return cls.normalize_language(qt_name)
        except Exception:
            pass

        for env_var in ("LC_ALL", "LANG", "LANGUAGE"):
            val = os.environ.get(env_var)
            if val:
                return cls.normalize_language(val)

        sys_loc, _ = locale.getlocale()
        if sys_loc:
            return cls.normalize_language(sys_loc)

        return "en-US"
